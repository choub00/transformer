def find_and_replace(doc, old_text, new_text):
    old_stripped = old_text.strip()
    new_stripped = new_text.strip()

    for para in doc.paragraphs:
        full = para.text
        if full.strip() == old_stripped:
            _replace_para(para, new_stripped)
            return True
        if old_stripped in full:
            updated = full.replace(old_stripped, new_stripped)
            _replace_para(para, updated)
            return True
    return False


def _replace_para(para, new_text):
    if not para.runs:
        para.add_run(new_text)
        return
    first_run = para.runs[0]
    first_run.text = new_text
    for r in para.runs[1:]:
        r.text = ""


